import { jsPDF } from 'jspdf'
import { useCallback } from 'react'
import type { Invoice } from '../types'
import { centsToAud } from '../utils/currency'
import {
  ABN,
  EXPENSE_CATEGORY,
  EXPENSE_SUBCATEGORY,
  SELLER_DETAILS,
} from '../utils/constants'
import {
  APP_ID_ASSET_VAULT,
  APP_ID_AFFILIATE,
  APP_ID_TIMELINE,
  traceInterlink,
} from '../utils/interlinks'

interface PdfExportButtonProps {
  invoice: Invoice | null
  onExport?: (blob: Blob) => void
  disabled?: boolean
}

const MARGIN = 15

export function PdfExportButton({ invoice, onExport, disabled = false }: PdfExportButtonProps) {
  const handleExport = useCallback(async () => {
    if (!invoice) return

    const doc = new jsPDF('p', 'mm', 'a4')
    const pageWidth = (doc.internal.pageSize.getWidth?.() ?? 210) as number
    let y = MARGIN

    const body = (size = 9) => {
      doc.setFont('helvetica', 'normal')
      doc.setFontSize(size)
    }
    const bold = (size = 9) => {
      doc.setFont('helvetica', 'bold')
      doc.setFontSize(size)
    }

    // ---------- Header ----------
    doc.setFont('helvetica', 'bold')
    doc.setFontSize(20)
    doc.text('TAX INVOICE', MARGIN, y)
    body()
    doc.text(`ABN: ${ABN}`, pageWidth - MARGIN, y, { align: 'right' })
    y += 12

    // ---------- Seller / Buyer blocks ----------
    const sellerX = MARGIN
    const buyerX = pageWidth / 2 + 5

    bold(10)
    doc.text('From', sellerX, y)
    doc.text('Bill To', buyerX, y)
    y += 7

    body()
    const sellerLines = [
      SELLER_DETAILS.name,
      SELLER_DETAILS.addressLine1,
      SELLER_DETAILS.addressLine2,
      `Email: ${SELLER_DETAILS.email}`,
      `Phone: ${SELLER_DETAILS.phone}`,
      `ABN: ${ABN}`,
    ]
    const buyerLines = [
      invoice.buyer.executiveName,
      invoice.buyer.companyEntityName,
      invoice.buyer.addressLine1,
      invoice.buyer.addressLine2,
      invoice.buyer.email,
      invoice.buyer.suburb,
      `${invoice.buyer.state} ${invoice.buyer.postcode}`,
    ].filter((line) => line.length > 0)

    const blockLines = Math.max(sellerLines.length, buyerLines.length)
    sellerLines.forEach((line, i) => doc.text(line, sellerX, y + i * 5))
    buyerLines.forEach((line, i) => doc.text(line, buyerX, y + i * 5))
    y += blockLines * 5 + 10

    // ---------- Invoice meta ----------
    body()
    doc.text(`Invoice #: ${invoice.invoiceNumber}`, MARGIN, y)
    doc.text(`Date: ${invoice.issueDate}`, MARGIN + 55, y)
    doc.text(`Due date: ${invoice.dueDate}`, MARGIN + 110, y)
    y += 11

    // ---------- Line items table ----------
    const colX = [MARGIN, MARGIN + 100, MARGIN + 130, MARGIN + 160, MARGIN + 185]
    const headers = ['Description', 'Qty', 'Ex GST (AUD)', 'GST (AUD)', 'Total (AUD)']

    doc.setFillColor(241, 245, 249)
    doc.rect(MARGIN, y, pageWidth - MARGIN * 2, 8, 'F')
    doc.setDrawColor(226, 232, 240)
    doc.rect(MARGIN, y, pageWidth - MARGIN * 2, 8, 'S')
    bold(8)
    headers.forEach((h, i) => doc.text(h, colX[i], y + 5.5))
    y += 9

    body()
    invoice.lines.forEach((line) => {
      doc.text(line.description, colX[0], y + 5.5)
      doc.text(String(line.quantity), colX[1], y + 5.5)
      doc.text(centsToAud(line.unitExGstCents), colX[2], y + 5.5, { align: 'right' })
      doc.text(centsToAud(line.gstCents), colX[3], y + 5.5, { align: 'right' })
      doc.text(centsToAud(line.totalCents), colX[4], y + 5.5, { align: 'right' })
      y += 7
    })

    // ---------- Totals ----------
    const totals = [
      { label: 'Ex GST', value: centsToAud(invoice.exGstCents), bold: false },
      { label: `GST (${10}%)`, value: centsToAud(invoice.gstCents), bold: false },
      { label: 'Total payable (incl. GST)', value: centsToAud(invoice.totalCents), bold: true },
    ]
    totals.forEach((t) => {
      if (t.bold) bold(10)
      else body(9)
      doc.text(t.label, MARGIN, y + 6)
      doc.text(t.value, pageWidth - MARGIN, y + 6, { align: 'right' })
      y += 7
    })
    y += 6

    // ---------- Expense category ----------
    bold()
    doc.text('Pre-coded expense category:', MARGIN, y)
    body()
    doc.text(`${EXPENSE_CATEGORY} / ${EXPENSE_SUBCATEGORY}`, MARGIN + 46, y)
    y += 9

    // ---------- Payment terms ----------
    body()
    doc.text('Payment terms: 14 days from invoice date. GST inclusive.', MARGIN, y)
    y += 5
    doc.text('Please quote the invoice number as the payment reference.', MARGIN, y)
    y += 13

    // ---------- Footer ----------
    doc.setDrawColor(226, 232, 240)
    doc.line(MARGIN, y, pageWidth - MARGIN, y)
    y += 8
    body(7)
    doc.setTextColor(100, 116, 139)
    doc.text(
      'Generated by Aurelia OS Expense Checkout & Tax Invoice Generator (App 06) • Recipient-created tax invoice • Retain for GST records.',
      MARGIN,
      y,
    )

    // jsPDF v2 returns a Blob synchronously; older typings may return a Promise — handle both.
    const raw = doc.output('blob') as unknown as Blob | Promise<Blob>
    const pdfBlob = raw instanceof Blob ? raw : await raw

    // Interlink: invoice PDF → 02 Asset Vault (cloud proof pointer)
    if (onExport) {
      onExport(pdfBlob)
    }
    traceInterlink(APP_ID_ASSET_VAULT, 'pdfExported', {
      invoiceNumber: invoice.invoiceNumber,
      bytes: pdfBlob.size,
    })

    const url = URL.createObjectURL(pdfBlob)
    const link = document.createElement('a')
    link.href = url
    link.download = `Tax Invoice ${invoice.invoiceNumber}.pdf`
    document.body.appendChild(link)
    link.click()
    document.body.removeChild(link)
    URL.revokeObjectURL(url)
  }, [invoice, onExport])

  return (
    <button
      onClick={handleExport}
      disabled={disabled || !invoice}
      className="flex items-center gap-2 w-full px-4 py-3 rounded-lg border border-slate-200 bg-white text-sm font-medium text-slate-700 transition-colors hover:bg-slate-50 disabled:opacity-50 disabled:cursor-not-allowed"
    >
      📄 Export Tax Invoice PDF
    </button>
  )
}

// Documented interlink entry points (wired by the host shell):
// - Invoice due dates   → 01 Timeline   (hard report deadline):  APP_ID_TIMELINE
// - Subscription tier   → 07 Affiliate Engine (attribution/commission): APP_ID_AFFILIATE
// - Invoice PDF         → 02 Asset Vault (cloud proof pointer):   APP_ID_ASSET_VAULT
export { APP_ID_TIMELINE, APP_ID_AFFILIATE, APP_ID_ASSET_VAULT }